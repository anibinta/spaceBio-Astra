export function generateDemoDataset(): {
  publications: Publication[];
  passages: Passage[];
  claims: Claim[];
} {
  const publications: Publication[] = [];
  const passages: Passage[] = [];
  const claims: Claim[] = [];

  let passageCounter = 1;
  let claimCounter = 1;

  for (const study of SEED_STUDIES) {
    const pubId = `DEMO-PUB-${String(study.num).padStart(3, '0')}`;
    publications.push({
      id: pubId,
      doi: `10.0000/demo-spacebio-${String(study.num).padStart(3, '0')}`,
      pmid: `DEMO-PMID-${90000 + study.num}`,
      title: study.titleEn,
      titleFr: study.titleFr,
      authors: study.authors,
      year: study.year,
      journal: study.journal,
      keywords: study.keywords,
      fullTextStatus: study.fullTextStatus,
      externalLinks: [
        {
          label: 'Portail NASA OSDR (référence plateforme)',
          url: 'https://osdr.nasa.gov/bio/repo',
          type: 'demo_placeholder',
        },
      ],
      license:
        'DONNÉES DE DÉMONSTRATION (CC-BY-4.0 synthétique) — À remplacer par le corpus réel NASA OSDR (608 publications).',
      language: 'en',
      autoTranslated: false,
      isDemoData: true,
    });

    let charCursor = 0;
    study.passages.forEach((p, idx) => {
      const passageId = `DEMO-PAS-${String(passageCounter++).padStart(3, '0')}`;
      const charStart = charCursor;
      const charEnd = charStart + p.textEn.length;
      charCursor = charEnd + 1;

      passages.push({
        id: passageId,
        publicationId: pubId,
        section: p.section,
        text: p.textEn,
        textFr: p.textFr,
        position: {
          paragraphIndex: idx,
          charStart,
          charEnd,
          pageLabel: `p.${idx + 1}`,
        },
        isAuthorInterpretation: p.isAuthorInterpretation,
        language: 'en',
        autoTranslated: true,
        isDemoData: true,
      });

      for (const c of p.claims) {
        const claimId = `DEMO-CLM-${String(claimCounter++).padStart(3, '0')}`;
        claims.push({
          id: claimId,
          passageId,
          publicationId: pubId,
          statement: c.statementEn,
          statementFr: c.statementFr,
          organism: c.organism,
          isModelOrganism: c.isModelOrganism,
          spaceCondition: c.spaceCondition,
          exposureDurationDays: c.exposureDurationDays,
          durationBucket: c.durationBucket,
          biologicalSystem: c.biologicalSystem,
          effectDirection: c.effectDirection,
          relationType: c.relationType,
          sampleSize: c.sampleSize,
          sampleUnit: c.sampleUnit,
          evidenceLevel: c.evidenceLevel,
          confidenceScore: c.confidenceScore,
          humanValidated: c.humanValidated,
          limitations: c.limitations,
          year: study.year,
          isDemoData: true,
        });
      }
    });
  }

  return { publications, passages, claims };
}
